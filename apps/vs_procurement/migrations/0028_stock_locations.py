def open_default_locations(apps, schema_editor):
    """Create MAIN per stock-holding entity, then attribute balances and history."""
    StockItem = apps.get_model("vs_procurement", "StockItem")
    StockLocation = apps.get_model("vs_procurement", "StockLocation")
    StockBalance = apps.get_model("vs_procurement", "StockBalance")
    StockMovement = apps.get_model("vs_procurement", "StockMovement")

    entity_ids = set(StockItem.objects.values_list("entity_id", flat=True))
    entity_ids |= set(StockMovement.objects.values_list("entity_id", flat=True))

    locations = {}
    for entity_id in sorted(entity_ids):
        location, _ = StockLocation.objects.get_or_create(
            entity_id=entity_id, code=DEFAULT_CODE,
            defaults={
                "name": DEFAULT_NAME,
                "description": "Created when stock gained a location dimension.",
                "is_default": True,
                "is_active": True,
            },
        )
        locations[entity_id] = location

    # Only items that actually hold something get a balance row. Creating one per
    # item would leave a table full of permanent zeroes.
    for item in StockItem.objects.exclude(on_hand_qty=0, stock_value=0):
        StockBalance.objects.get_or_create(
            stock_item=item, location=locations[item.entity_id],
            defaults={
                "on_hand_qty": item.on_hand_qty,
                "stock_value": item.stock_value,
            },
        )

    for entity_id, location in locations.items():
        StockMovement.objects.filter(
            entity_id=entity_id, location__isnull=True,
        ).update(location=location)


def close_default_locations(apps, schema_editor):
    """Unpick the attribution. The item totals were never touched, so nothing is lost."""
    StockLocation = apps.get_model("vs_procurement", "StockLocation")
    StockBalance = apps.get_model("vs_procurement", "StockBalance")
    StockMovement = apps.get_model("vs_procurement", "StockMovement")

    StockMovement.objects.filter(location__isnull=False).update(location=None)
    StockBalance.objects.all().delete()
    StockLocation.objects.filter(code=DEFAULT_CODE).delete()


