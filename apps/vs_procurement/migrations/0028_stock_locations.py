"""Give stock a location, and attribute everything that already exists to one.

Stock was one pool per entity. The pool knew a thousand units existed; it could not
know that seven hundred stood at one campus and three hundred at the other, so an issue
at the smaller site drew against stock it did not have and the availability check
allowed it. Quieter and just as wrong: one blended average meant a site that bought
dearer and a site that bought cheaper both relieved inventory at the middle, so each
one's expense was off in opposite directions.

This adds :class:`StockLocation` and :class:`StockBalance`, and a location on every
movement. The item's own ``on_hand_qty`` and ``stock_value`` stay exactly as they are
and become the roll-up across locations, which is what lets every existing report,
serializer and reorder rule keep reading the same numbers.

What the data step does, and what it deliberately does not:

* every entity that holds stock items gets one location, ``MAIN``, marked default;
* each item carrying quantity or value gets one balance row at ``MAIN`` holding its
  current totals verbatim, so no value is created or destroyed;
* every existing movement is attributed to ``MAIN``.

Attributing all history to one location is the honest answer, not a convenient one: the
old data records no location, so any split across campuses would be invented. A school
that has been running two campuses should create its second location and transfer the
opening balances deliberately, where the transfer is visible, rather than have this
migration guess.

Reverse drops the balances and locations and clears the movement links. The item totals
are never touched in either direction, so the reverse is lossless.
"""
